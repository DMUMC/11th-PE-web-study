async function request(title, method, path, body, token, expected, code) {
  const response = await fetch(api + path, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const data = await response.json();
  assert.equal(response.status, expected, title + JSON.stringify(data));
  if (code) assert.equal(data.code, code);
  records.push({ title, method, path, authorization: token ? 'Bearer [실제 발급 토큰]' : '없음', request: body, status: response.status, response: data });
  return data.result;
}
