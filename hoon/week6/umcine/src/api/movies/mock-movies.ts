export function getMockMovieList(page: number = 1): TmdbMovieListResponse {
  const pageSize = 5;
  const start = (page - 1) * pageSize;
  const results = MOCK_MOVIES.slice(start, start + pageSize);
  return {
    page,
    results,
    total_pages: Math.ceil(MOCK_MOVIES.length / pageSize),
    total_results: MOCK_MOVIES.length,
  };
}

